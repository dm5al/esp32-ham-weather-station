const char *T(str_id_t id)
{
    if (id >= S_COUNT) {
        return "";
    }
    lang_t l = prefs_lang();
    const char *s = k_str[id][l];
    /* Fall back to English rather than drawing nothing: a missing translation
     * should look untranslated, not look broken. */
    if (!s || !s[0]) {
        s = k_str[id][LANG_EN];
    }
    return s ? s : "";
}

const char *lang_name(lang_t l)
{
    /* Native names: a user hunting for their own language scans for the word
     * they know, not for its English exonym. */
    static const char *const k_names[LANG_COUNT] = {
        "English", "Deutsch", "Русский", "Français", "Italiano", "Español",
    };
    return (l < LANG_COUNT) ? k_names[l] : "English";
}
